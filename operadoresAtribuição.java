package semana2.operadores;

public class operadoresAtribuição {
    public static void main(String[] args) {

        int a = 1;
        int b = 2;
        int c = 3;

        c -= a; // c = c - a
        c += b; // c = c + b
        c *= a; // c = c * a
        c /= b; // c = c * b
        c++; // c = c + 1
    }
}
